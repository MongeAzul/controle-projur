-- ---------------------------------------------------------------------------
-- Quem pode entrar: só os e-mails cadastrados aqui.
-- papel 'editor' cadastra e altera; 'leitor' só consulta e exporta.
-- Gerencie pelo Table Editor do Supabase (a página não altera esta tabela).
-- ---------------------------------------------------------------------------
create table if not exists public.membros (
  email text primary key,
  nome text,
  papel text not null default 'editor' check (papel in ('editor', 'leitor'))
);

create or replace function public.papel_atual() returns text
language sql stable security definer set search_path = public as $$
  select papel from public.membros where lower(email) = lower(auth.jwt() ->> 'email')
$$;

-- ---------------------------------------------------------------------------
-- Tabelas do sistema
-- ---------------------------------------------------------------------------
create table if not exists public.processos (
  id text primary key default gen_random_uuid()::text,
  seq integer generated by default as identity unique,
  tipo text not null,
  numeros jsonb not null default '[]',
  numero_texto text,
  responsavel text,
  chegada date,
  prazo date,
  situacao text not null default 'Em análise'
    check (situacao in ('Em análise', 'Acompanhando', 'Esperando', 'Prazo aberto', 'Finalizado')),
  descricao text,
  andamentos jsonb not null default '[]',
  atualizado_em date,
  finalizado_em date,
  origem text not null default 'sistema',
  criado_em timestamptz not null default now()
);

create table if not exists public.equipe (
  id text primary key,
  nome text not null,
  ativo boolean not null default true
);

create table if not exists public.ferias (
  id text primary key default gen_random_uuid()::text,
  pessoa text not null,
  inicio date not null,
  fim date not null,
  tipo text,
  check (fim >= inicio)
);

-- ---------------------------------------------------------------------------
-- Histórico: toda inclusão, alteração e exclusão fica registrada com o e-mail de quem fez.
-- ---------------------------------------------------------------------------
create table if not exists public.historico (
  id bigint generated always as identity primary key,
  tabela text not null,
  registro_id text not null,
  acao text not null,
  antes jsonb,
  depois jsonb,
  email text,
  em timestamptz not null default now()
);

create or replace function public.registrar_historico() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.historico (tabela, registro_id, acao, antes, depois, email)
  values (
    tg_table_name,
    coalesce(new.id, old.id),
    lower(tg_op),
    case when tg_op <> 'INSERT' then to_jsonb(old) end,
    case when tg_op <> 'DELETE' then to_jsonb(new) end,
    auth.jwt() ->> 'email'
  );
  return coalesce(new, old);
end $$;

drop trigger if exists historico_processos on public.processos;
create trigger historico_processos after insert or update or delete on public.processos
  for each row execute function public.registrar_historico();
drop trigger if exists historico_equipe on public.equipe;
create trigger historico_equipe after insert or update or delete on public.equipe
  for each row execute function public.registrar_historico();
drop trigger if exists historico_ferias on public.ferias;
create trigger historico_ferias after insert or update or delete on public.ferias
  for each row execute function public.registrar_historico();

-- ---------------------------------------------------------------------------
-- Regras de acesso (RLS): sem login ou fora de "membros", nada é visível.
-- ---------------------------------------------------------------------------
alter table public.membros enable row level security;
alter table public.processos enable row level security;
alter table public.equipe enable row level security;
alter table public.ferias enable row level security;
alter table public.historico enable row level security;

drop policy if exists "membro ve o proprio cadastro" on public.membros;
create policy "membro ve o proprio cadastro" on public.membros
  for select to authenticated using (lower(email) = lower(auth.jwt() ->> 'email'));

do $$
declare t text;
begin
  foreach t in array array['processos', 'equipe', 'ferias'] loop
    execute format('drop policy if exists "membros leem" on public.%I', t);
    execute format('drop policy if exists "editores incluem" on public.%I', t);
    execute format('drop policy if exists "editores alteram" on public.%I', t);
    execute format('drop policy if exists "editores excluem" on public.%I', t);
    execute format('create policy "membros leem" on public.%I for select to authenticated using (public.papel_atual() is not null)', t);
    execute format('create policy "editores incluem" on public.%I for insert to authenticated with check (public.papel_atual() = ''editor'')', t);
    execute format('create policy "editores alteram" on public.%I for update to authenticated using (public.papel_atual() = ''editor'') with check (public.papel_atual() = ''editor'')', t);
    execute format('create policy "editores excluem" on public.%I for delete to authenticated using (public.papel_atual() = ''editor'')', t);
  end loop;
end $$;

drop policy if exists "membros leem" on public.historico;
create policy "membros leem" on public.historico
  for select to authenticated using (public.papel_atual() is not null);

-- ---------------------------------------------------------------------------
-- Atualização ao vivo: as telas abertas recebem as mudanças feitas por outras pessoas.
-- ---------------------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array['processos', 'equipe', 'ferias'] loop
    if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = t) then
      execute format('alter publication supabase_realtime add table public.%I', t);
    end if;
  end loop;
end $$;
